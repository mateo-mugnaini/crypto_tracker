const messages = {
  es: { ...es, ...supplement.es },
  it: { ...it, ...supplement.it },
  en: { ...en, ...supplement.en },
};
const interpolate = (value, variables) =>
  variables
    ? value.replace(/\{(\w+)\}/g, (_, key) => String(variables[key] ?? ""))
    : value;
function readLocale() {
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "it" || stored === "es" || stored === "en" ? stored : "it";
}
const fallbackContext = {
  locale: "es",
  setLocale: () => undefined,
  t: (key, variables) => interpolate(es[key] || key, variables),
};
const I18nContext = createContext(fallbackContext);
export function I18nProvider({ children }) {
  const [locale, setLocaleState] = useState(readLocale);
  const setLocale = (nextLocale) => {
    setLocaleState(nextLocale);
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
  };
  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (key, variables) =>
        interpolate(messages[locale][key] || es[key] || key, variables),
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
export function useI18n() {
  return useContext(I18nContext);
}
