const messages: Record<Locale, Messages> = {
  es: { ...es, ...extras.es },
  it: { ...it, ...extras.it },
  en: { ...en, ...extras.en },
};

function interpolate(value: string, variables?: Variables) {
  const decoded = value.replace(/\\u([0-9a-f]{4})/gi, (_, code: string) =>
    String.fromCharCode(parseInt(code, 16)),
  );
  return variables
    ? decoded.replace(/\{(\w+)\}/g, (_, key: string) => String(variables[key] ?? ""))
    : decoded;
}

function readLocale(): Locale {
  if (typeof window === "undefined") return "it";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "it" || stored === "es" || stored === "en" ? stored : "it";
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, variables?: Variables) => string;
}
const fallbackContext: I18nContextValue = {
  locale: "es",
  setLocale: () => undefined,
  t: (key, variables) => interpolate(es[key] ?? key, variables),
};
const I18nContext = createContext<I18nContextValue>(fallbackContext);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale);
  function setLocale(nextLocale: Locale) {
    setLocaleState(nextLocale);
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
  }
  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, variables) =>
        interpolate(messages[locale][key] ?? es[key] ?? key, variables),
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
